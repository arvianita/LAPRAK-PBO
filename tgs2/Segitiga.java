public class Segitiga {
    public static void main(String[] args) {
         double a = 6;
        double b = 8;
        double luas = 0.5 * a * b;
        System.out.println("Luas segitiga = " + luas);
        
        System.out.println("\n\nProgram mencari nilai c");
        double c = Math.sqrt(a * a + b * b);
        System.out.println("Nilai c pada segitiga = " + c);
    }
}
    
    
